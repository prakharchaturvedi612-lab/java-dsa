package _01_Bsics;

public class _03_updatingvariables {
    public static void main (String[] args) {
        int x = 8 ;
        System.out.println(x)  ;
         x = 4 ;
        System.out.println(x)  ;
         x = x + 10 ;
        System.out.println(x)   ;
         x = x - 5 ;
         System.out.println(x)  ;
        x = x * 10 ;
        System.out.println(x);
        x = x / 2 ;
        System.out.println(x);








    }







}
