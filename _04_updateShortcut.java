package _01_Bsics;

public class _04_updateShortcut {
    public static void main(String[] args) {
         int x = 2 ;
        System.out.println(x);
        x += 3 ; // x = x + 3
        System.out.println(x);
        x -= 1 ; // x = x - 1
        System.out.println(x);
        x *= 4 ; // x = x * 4
        System.out.println(x);
        x /= 8 ; //  x = x / 8
        System.out.println(x);









    }








}
